//! xenolith がなぜこのような構造をしているか。
//!
//! このモジュールは API を持たない。設計の各部分について、何を決めたか、どの案を採らなかったか、その結果どうなるか
//! を記録する場所である。使い方・動作・組み合わせ方は、ほかの各項目の doc に書く。
//!
//! **ドラフト。** レビューで設計がまだ変わるため、今は「何を書くか」のリストだけを置く。各項目は後で 1 ページ
//! （サブモジュール）か、その中の節になる。名前は doc 内リンクにせずコード表記で書く。レビュー中の名前変更で doc
//! ビルドが壊れないようにするためで、本文を書くときにリンクへ直す。本文は他の doc と同じく英語で書く。
//!
//! 各ページの型の案: Context（何が問題か）、Decision（どう決めたか）、Alternatives not taken（採らなかった案と
//! 理由）、Consequences（結果として何ができて何ができないか。それを体現する項目へのリンク）。
//!
//! # 書くこと
//!
//! ## 検証
//!
//! - 文書を検証する 3 つの層と、それぞれが受け持つもの:
//!   - パーサ: 読むために読みながら検証しなければならないもの。要素の入れ子、ルート要素が 1 つであること、ルート
//!     要素の外のテキストと参照、`DOCTYPE` の位置と回数、エンティティ境界、`Char`、名前空間の束縛、`xml:space`。
//!   - `StrictXmlConstraints`: 任意のイベント列が整形式かつ名前空間整形式の文書であることを検証し、最初の違反で
//!     `Err` を返して止める。
//!   - `Validator`（DTD などのスキーマ）: 妥当性を検証し、エラーをすべて保持して処理を続ける。
//! - 整形式違反は致命的で妥当性違反は回復可能とした理由と、その区別を重大度ではなく型（`Error` と
//!   `ValidityError`）で表す理由。`Severity` は削除した。
//! - パーサが 4 つの字句の検証（名前が `QName` か、属性の重複、コメントの `--`、PI のターゲット）を消費者に残す
//!   理由: 入力を信頼できるアプリケーションは省略できる。パーサから来たイベントには
//!   `StrictXmlConstraints::lexical_only` でこの 4 つだけを検証できる。
//! - それ以外の検証をパーサから validator へ移せなかった理由:
//!   - `DOCTYPE` を読むと、イベントを報告する前に DTD を読み、外部サブセットを解決しうる。ルート要素の外の参照は
//!     展開される。validator が拒否できるのはそれらの副作用の後になる。
//!   - イベントはどのエンティティから来たかを持たないので、エンティティ境界の規則はイベントからは判定できない。
//!   - パーサは名前空間スコープ、`xml:space`、`xml:lang`、基底 URI、深さ制限のために開いた要素のスタックをどのみち
//!     持つので、それを使う検証のコストはほぼない。
//! - `StrictXmlConstraints` がパーサを前提にしない理由: イベントは木の走査（`DomSource`）、保存した `Event` の
//!   再生、手で組み立てるプログラムからも来て、構造の一部しか自分で検証しない `XmlWriter` にも渡る。
//! - `XmlWriter` が何を検証するか、直接の呼び出しでは panic し、イベント消費者としては `Err` を返す理由: 呼び
//!   出しの誤用は呼び出し側コードの誤りだが、イベントはどこからでも来うる。
//! - 「Loose XML」の定義: `StrictXmlConstraints` を通していないイベント列の文書。XML であるかもしれないが、それを
//!   示したものがない。
//! - Loose XML を補正する消費者（`LooseRebuilder`）を削除した理由: XML 仕様の外なので、イベント列を「良い感じに
//!   補正する」規則は仕様から導けず、今の段階では決められない。補正しないので、ROADMAP の「loose parsing は対象外」
//!   とも矛盾しない。
//! - facade である `Reader` が `lexical_only` ではなく完全版の `StrictXmlConstraints` で検証する理由と、
//!   `with_strict(false)` が補正せずに Loose XML をそのまま渡す理由。
//! - アプリケーションが自分の事情で 1 つの規則だけを緩める方法: `StrictXmlConstraints` を包み、validator に見せる
//!   ものを変える（コメントの `--` を許す例: 次もダッシュであるダッシュを置き換え、位置と末尾のダッシュを保つ）。
//!   エラーを捕まえて無視する方法を採らない理由: メッセージ文字列に依存し、同じイベントの後続の検証を隠す。エラー
//!   は variant より細かい種類を持たない。
//! - `StrictXmlConstraints` が開いた要素をインターンした名前でなく `String` で持つ理由: イベントは `&str` を運ぶので
//!   インターンすると名前をもう一度ハッシュすることになり、プールは文書中の異なる名前の数だけ大きくなる。
//! - `StartDocument` ごとに validator をリセットし、状態を作り直すのではなくクリアする理由。
//! - `StrictXmlConstraints` は文書の途中に来た `StartDocument` を整形式エラーにする（`EndDocument` は以前から
//!   検出していた）。アプリケーションが別の文書を取り込むときに、取り込んだ文書自身の `StartDocument` や
//!   `EndDocument` を誤って流すのを見つけるため。
//!   - 以前は `StartDocument` が来るたびに状態を作り直していたので、途中の `StartDocument` は検査のやり直しになり、
//!     見逃していた。
//!   - 途中で止まった実行（`EndDocument` が来ない）の後に次の文書へ進めるよう、`finish` で文書の外（`Outside`）に
//!     戻す。ソースは実行の終わりに必ず `finish` を呼ぶので、使い回しはそのまま動く。イベントを手で渡す呼び出し側
//!     は、`EndDocument` まで届かなかった実行の後に `finish` を呼ぶ必要がある（doc に記載）。
//!   - エラーの位置は、開いている最も内側の要素（取り込んだ場所）。`StartDocument` は位置を持たないため。
//! - 複数の validator のまとめ役を、ソースを駆動する実行（旧 `ValidatingSource` / `Validatable` / `run`）ではなく、
//!   1 つの消費者 `ValidatorSet` にした理由: 駆動は `emit` で足り、本体は validator のとりまとめと結果の `Report`
//!   化だった。消費者なら push・pull・手で送るのどれでも同じに使え、ソースより先に作るので `'h` の問題も起きず、
//!   終了は `finish` で届く。アプリケーションの消費者は中に入れず `Dispatcher` に並べる（役割の重複を避ける）。
//!   `ValidatorSet` 自身も `Validator` なので、出力の前段に置いて書く前に検証させることもできる。
//!   - `Report` に終わり方（`Ended`）を含める理由: 文書全体を要する検査は完了した処理でしか行われない。
//!     `is_valid` は「完了し、何かに対して検証し、エラーがない」。
//!   - `Validator::errors` が `Cow<'_, [ValidityError]>` を返し、順序を約束しない理由: `ValidatorSet` が実行中に
//!     エラーを取り込む（取り込み済み件数 `taken` と位置順の挿入）と、拒否と同じ呼び出しで記録されたエラーの
//!     取りこぼしなど扱いが込み入る。呼ばれたときに各 validator から集めれば済む。自分で保持する validator は
//!     `Borrowed` で費用がかからず、集める側だけが `Owned` を返す。
//!   - `Report` のエラーを位置で並べる理由と方法: validator ごとの報告時期（即時か `EndDocument` か）に関係なく
//!     文書の順で読めるようにする。システム識別子、行、桁の順で、位置不明は最後。同じ位置は validator の順（安定
//!     ソート）。上限を超えたときに返すのは、この順で `max + 1` 番目のエラー。
//!   - エラー数の上限（`with_max_errors`）: 1 件で止めたいアプリケーションと、まとめて直したい人の両方のため。
//!     上限を超えたエラーを `Err` で返して処理を止める（`Flow::Break` では `Dispatcher` の他の消費者が止まらない
//!     ため）。既定は上限なし（`None`）。
//!     - 件数は各 validator が `consume` の戻り値で報告したものを数える。報告が実際より少ない validator には上限が
//!       効かない。
//!     - 件数の加算は飽和加算にする（`Dispatcher`、`ValidatorSet`、XInclude の変換）。件数はアプリケーションの
//!       消費者からも来るので、過大な値で桁あふれさせると debug では panic し、release では回り込んで上限を
//!       すり抜ける。飽和すれば上限を必ず超え、`Err` で止まる。
//!     - 値は「許容する最大数」で、`Some(0)` は 1 件目で止まる。以前の `with_error_limit(n)` は「n 件目で止まる」で、
//!       `Limits::max_depth` などの「そこまで許す数」と意味が逆に読めたため改めた（旧 `n` は新 `Some(n - 1)`）。
//!     - 引数は `Option<usize>` で、`None` が上限なし。`0` を「上限なし」に読み替える特別扱いをやめ、一度付けた上限を
//!       外すこともできるようにした。`Limits` のフィールドと同じ表し方。
//!   - 利用者が追加した validator は作り直さず、`StartDocument` で自身がリセットすることを要求する（リセットしない
//!     と前の文書のエラーも数えられる）。DTD と `xml:id` の validator は文書ごとに作り直す。
//! - 書く前に決めること: PI のターゲットやエンティティ名のコロン（Namespaces in XML §7）はパーサも validator も
//!   検証していない。`DOCTYPE` の名前は `QName` ではなく `Name` として検証している。`EndDocument` はそれ自身の位置を
//!   持たないので、閉じていない要素は開始タグの位置（`OpenElement` が保持する）で報告し、ルート要素がない場合は位置
//!   なしで報告する。
//!
//! ## イベント
//!
//! - すべての生産者と消費者が 1 つの語彙を使うこと: パーサ、木の走査、ビルダー、validator、writer は `EventRef` で
//!   つながる。生産者と消費者が特定の実装に結びつかないトレイトである理由。
//! - `EventRef`（1 回のコールバックのための借用）と `Event`（その後も保持する所有）の分担と、両方が存在し相互に
//!   変換できる理由。
//! - 種類ごとにペイロード構造体（`StartElementEventRef`、`StartElementEvent` など）を持ち、enum にフィールドを
//!   直接置かない理由: 1 種類のイベントを扱う関数がその構造体を受け取れる。`#[non_exhaustive]` と `new` でフィー
//!   ルド追加の余地を残す。
//! - 所有の `DoctypeEvent` が `Arc<Dtd>` と fork した `NamePool` を持つ理由。
//! - パーサ固有の層: `TokenRef` と `TokenKind` はパーサが生成するもので、XML 宣言はそこにだけ存在し、イベントの
//!   語彙には含まれない。スキャナが独自の型を持たず `TokenKind` を共有する理由。
//! - `EventCursor::next` がイベントを返す前に登録済み消費者を呼ぶ理由（push と pull が 1 回の処理になり、pull
//!   したイベントはソースに登録した検証を通過済みになる）。
//! - `EventCursor` が `Iterator` になれない理由（イベントがカーソルを借用する）と、`events()` が `Event` へ複製
//!   してイテレータを提供し、最初のエラーの後で終わる理由。
//! - `Dispatcher`: 1 つの消費者の `Err` でそのイベントを即座に止める。`Flow::Break` を返した
//!   消費者はその処理の残りから外し、消費者ごとに記録して `StartDocument` でクリアするので、パイプラインを
//!   複数の文書に使い回せる。消費者のない dispatcher は処理を終わらせない。
//! - `EventConsumer::consume` が `Result<Flow>` を返す（`should_continue` は廃止）。
//!   - 名前は旧 `handle`。何をするのかが名前から読めないため、トレイト名と対になる `consume` に改めた。
//!   - `Break` はその消費者が処理を終えたこと、`Continue` は続けることを表す。どちらも、このイベントでその消費者
//!     とその下流が見つけた妥当性エラーの件数を運ぶ。件数は差分で、上流で合算する。
//!   - 理由: 妥当性エラーの件数を上流へ伝える手段が要る。入れ子の dispatcher や変換の内側で見つかったエラーにも、
//!     上流で付けた上限を効かせるため。
//!   - 伝えるのは件数だけ。エラーそのもの（`ValidityError`）は、処理を駆動した側が自分で所有する各 `Validator`
//!     から集める。
//!   - `Flow` は std の `ControlFlow<usize, usize>` の別名。そのまま書くと煩雑なため名前を付けた。別名なので
//!     `Flow::Continue(0)` と書け、`is_break` など `ControlFlow` のメソッドもそのまま使える。
//! - `Dispatcher` は消費者（`add_consumer`）と validator（`add_validator`）を区別する。処理を終えるのは、すべての
//!   消費者が `Break` したとき、または妥当性エラーの件数が上限（`with_max_errors`）を超えたとき。
//!   - 理由: validator は自分からは止まらない。validator も数えると、消費者が止まった後も、前に立つ
//!     `StrictXmlConstraints` などが処理を読み続けさせる。
//! - XInclude の変換が件数と停止を上流へ返す方法: 取り込んだ文書のイベントは入れ子のレーンを通り、そのソースは
//!   件数を返さない。そこで下流が返した件数は `XIncludeProcess` に貯め、`XIncludeTransformer` が上流のイベントへの
//!   応答として返す。下流の停止は `Dispatcher::is_stopped` で知り、取り込み（`parse="text"` を含む）を打ち切る。
//!   - 代償: 上流の上限の判定は上流のイベントごとなので、取り込みで見つかったエラーは、その取り込みを読み終えた
//!     後に `xi:include` の位置で上限に掛かる。
//! - 語彙の改名: `EventSource` → `EventProducer`、`EventHandler` → `EventConsumer`、`Dispatch` → `Dispatcher`。
//!   具体的な型（`StreamSource`、`DomSource`、`WriterSource`）は名前を変えない。
//!   - 消費者を足すメソッドは、値で受けて返すビルダーの `add_consumer`。`with_*` は「置き換える」と読めるため
//!     採らない。validator を足すメソッドも同列に `add_*` とする（`Dispatcher::add_validator`、
//!     `ValidatorSet::add_validator` / `add_validators` / `add_schema`。旧 `with_validator` など）。
//!   - `Validator::as_event_handler` は `as_consumer` に改めた。
//!   - `&mut self` を取る版（旧 `add` と旧 `add_validator`、一時 `push_consumer`）は公開しない。
//!     `add_consumer` は `self` を値で受けるので、`Dispatcher` をフィールドに持つ transformer も
//!     `self.dispatch = self.dispatch.add_consumer(handler)` と書ける（フィールドを持つ型が `Drop` を実装しない
//!     限り、値の取り出しと付け直しができる）。借用しか持たない利用場面はなく、同じことをする公開メソッドが 2 つ
//!     あるだけになるため。
//! - Constraints、Transformer、Filter はトレイトではなく概念上の種類で、その種類の型の名前に表す。
//!   - Constraints: どの違反の後も処理を続けられない validator（`StrictXmlConstraints`、`RootElementConstraints`）。
//!     旧 `StrictXmlValidator`。
//!   - Transformer: イベントを書き換え、足し、取り除く中段（`XIncludeTransformer`、旧 `XIncludeTransform`）。
//!   - Filter: イベントを選ぶだけの中段（`XPointerFilter`）。
//! - 処理の終わりを `EventConsumer::finish` と `Outcome`（`Completed`、`Stopped`、`Failed`）で知らせる理由: 消費者
//!   が書きかけのファイルなど、文書のために持ったリソースを後始末できるようにする。
//!   - `EndDocument` に結果を載せない理由: 消費者 A、B、C が並んでいて B が `EndDocument` でエラーを返すと、A は
//!     正常終了したように、C はエラーで中断したように見え、消費者ごとに観測する結果が食い違う。最後に `finish` で
//!     全消費者に同じ結果を知らせれば、全員が同じ処理結果を観測できる。`EndDocument` は文書が完結したことを表す
//!     語彙のままにし、所有 `Event` や再生に処理の実行状態を持ち込まない。
//!   - 途中で外れた消費者とエラーを返した消費者本人にも知らせる理由（後始末はどちらにも要る）。
//!   - ソースが `finish` を呼ぶのは `next` が最初に `None` を返したときとエラーを返したとき。エラーの後は `next` が
//!     `None` を返す。
//!   - `finish` の戻り値を `()` にした理由（後始末の失敗を報告する手段は持たない）。
//!   - 途中で放棄された処理も `Outcome::Abandoned` で知らせる理由と方法: pull を途中でやめた場合、ソースを駆動する
//!     側が自分の事情で打ち切った場合、panic で巻き戻る場合。個々のソース
//!     ではなく `Dispatcher` が「処理中か」（`StartDocument` 以降で `finish` 前）を持ち、`Drop` で知らせるので、どの
//!     ソースでも同じように働く。代償: `Dispatcher` が `Drop` を持つので、借りた消費者は dispatcher（とそれを持つ
//!     ソース）より長く生きる必要があり、ソースが生きている間は消費者を読めない。巻き戻り中に `finish` が呼ばれる
//!     ので、`finish` は panic してはならない。`StartDocument` を受け取っていない消費者には何も知らせない。
//! - **ルート要素の外の空白もイベントとして流す**（`Characters`）。XML 宣言、DOCTYPE、コメント、PI、ルート要素の
//!   間と前後に書かれた空白（`Misc` の `S`）。StAX と同じ立場で、Infoset・DOM・XPath のデータモデルとは異なる。
//!   - 理由: 読んで書き戻す流れ（`StreamSource` → `XmlWriter`）で、入力のトップレベルの改行が保たれる。以前は
//!     パーサが捨てていたため、宣言の後の改行などが失われ、ツリーでも補えなかった（DOM は文書ノードの直下に
//!     テキストを置けない。これは DOM Level 3 Core の規定どおり）。
//!   - 各部品の扱い: パーサは空白だけの並びを報告し、それ以外の文字は従来どおり整形式の違反。`DomBuilder` は
//!     読み飛ばす（文書の内容ではないため）。`XmlWriter` は受け取ったものを何でもそのまま書く。空白以外の文字と
//!     CDATA を拒否するのは前段の `StrictXmlConstraints` の役目で、writer は検査しない（責務の分担）。DTD の検証器は
//!     従来から空白を許していた。
//!   - XInclude は取り込んだ文書のトップレベルの空白を渡さない。§4.2.1 が取り込む対象を「文書情報項目の子」と
//!     定めており、空白はそこに含まれない（コメントと PI は含まれるので渡す）。`parse="text"` のテキストは取り込み
//!     そのものなので、この扱いを受けない。
//!   - 案 A（イベントにも含めず、見た目は writer が付ける）は、入力の書式を保てないので採らなかった。
//!   - `DomSource` から空白を送る手段は未定（次の作業）。
//!
//!
//! ## 名前
//!
//! - 名前を `NamePool` にインターンする理由と、同一性を文書ではなくプールが持つ理由。
//! - プールを clone せず `fork` する理由: 同じ同一性を保った clone にインターンすると、異なる名前に同じ `NameId`
//!   を発行してしまう。fork 元が発行したハンドルを解決するための（プール, 範囲）の系譜、ハンドルを発行元のプール
//!   に正規化すること、`owns`、`resolve` が `pool#index` を示して panic する理由。
//! - `NameId` のプールに `NonZeroU32` を使う理由: コンパイラは決して現れない値を `None` の表現に使うので、
//!   `Option<NameId>` が 8 バイトに収まる。予約名はルートプールに置く。
//!
//! ## エラーと位置
//!
//! - `Location::new`（1 行 1 桁）と `Location::unknown` の違い、未知の位置を `advance` しても未知のままにする理由
//!   （木の走査は位置を報告せず、イベント内部を指す検証が位置をでっち上げてはならない）。
//! - 位置の `Display` がシステム識別子か `<unknown>` を出し、分かっていれば行と桁を続ける理由。
//! - `Error::or_at` がある理由: `UriResolver` には参照の位置が渡されないので、呼び出し側が知っている位置を付ける。
//!   システム識別子だけを持つエラーはそれを保つ理由。
//! - `Error::encoding` が構築時にバイトオフセットを受け取る理由。
//!
//! ## 属性
//!
//! - `AttributeList` を、何が保持していても開始タグの属性を見る唯一のビューとすること。`AttributeRef`（借用）と
//!   `Attribute`（所有）、属性を所有する必要のある部品が独自の構造体ではなく `Vec<Attribute>` を使う理由。
//! - 名前空間宣言かどうかを `AttributeRef::declares_namespace()` / `Attribute::declares_namespace()` のメソッドに
//!   した理由: 名前（`xmlns` または接頭辞 `xmlns`）から決まる値なので、フィールドとして持つと名前と食い違う属性を
//!   作れてしまい、それを拒否する規則が要った。作る側（DOM の走査、writer、修復、テスト）が同じ式を書く手間もなく
//!   なる。パーサ内部の属性は名前空間解決の途中で使うので自分のフラグを持つ。
//! - DTD 検証が名前空間宣言も他の属性と同じく検証する理由: XML 1.0 の妥当性は名前空間を知らないので、妥当な文書は
//!   `xmlns` や `xmlns:p` を ATTLIST で宣言する（XHTML の DTD が `xmlns` を `#FIXED` で宣言するのはこのため）。以前は
//!   宣言を飛ばしていたので、宣言されていない `xmlns` も `#FIXED` と異なる値も見逃していた。
//! - 属性が自分の位置（`location` = 名前の開始、`value_location` = 値の先頭）を持つ理由: 検証が「どこが悪いか」を
//!   要素ではなく属性で、値の中の違反なら値の中の位置で示せるようにする。PI の `location` と `data_location` と同じ
//!   考え方。
//!   - 代償: `Location` が `Copy` でないため `AttributeRef` から `Copy` を外した。`get` 1 回ごとに `Location` を
//!     2 つ複製する（`system_id` は `Arc<str>` なので参照カウントの増加）。
//!   - 位置が未知になる場合: 木が持つ属性（木は位置を持たない）、writer の呼び出しで作られた属性、プログラムが
//!     組み立てた属性。
//!   - DTD の既定値で補われた属性は文書に書かれていないので、補われた開始タグの位置にしている（未知ではなく）。
//!   - 値の位置は正規化後の値に対するものなので、参照の展開や改行の正規化の分だけ元の文書とはずれる。
//!
//! ## 読み込みと書き出し
//!
//! - sans-I/O のパーサ（ROADMAP の決定 7）: パーサはバイト列を与えられて進捗を報告し、読むのはドライバ。不完全な
//!   トークンを保持し、入力が補充されたら先頭から再スキャンする方式。
//! - 呼び出し側が resolver を置かない限り何も取りに行かず、それなしの参照は黙って飛ばさず理由を示して拒否する理由。
//! - StAX 風の書き出し API を、イベントを出す側（`WriterSource`）と、イベントをバイト列に書く側（`XmlWriter`）に
//!   分けたこと。
//!   - 分ける理由: アプリの呼び出しがイベントになれば、出力先は消費者が決める。`XmlWriter` に送れば XML テキスト、
//!     `DomBuilder` に送れば DOM、`ValidatorSet` を前段に置けば書く前に検証、と組み合わせが自由になる。
//!   - `WriterSource` は push 型なので `EventProducer` だけを実装し、`EventCursor` は実装しない。
//!   - 終了通知は明示的な `finish()` を作らず自動にした。`end_document()` が `EndDocument` の後に `Completed` を出し、
//!     早期終了は `Stopped`、拒否は `Failed`、`end_document()` を呼ばずに drop すれば `Dispatcher` の `Drop` が
//!     `Abandoned` を出す。
//!   - 開始タグは属性がそろうまで保留して `StartElement` 1 つにまとめる。その代償として、属性が原因のエラー
//!     （エンコーディングで表せない名前など）は、その属性を書いた呼び出しではなく次の呼び出しで報告される。
//!   - 名前空間はアプリが `write_start_element_ns` で明示する。宣言のない接頭辞の使用は `StrictXmlConstraints` が
//!     検出できるので、ソース側では解決も補完もしない。
//!   - DTD と `NamePool` は `write_doctype` の引数で渡す。ソースに `with_dtd` として持たせると、それを読むのは
//!     `Doctype` イベントだけなので、ルート要素を書いた後に設定しても黙って捨てられる。渡す場所と使う場所を
//!     一致させて、設定が死ぬ経路をなくす。
//!   - `end_document()` の `EndDocument` は `settle` を通さない。ここで消費者が終了を示しても、それは
//!     `EndDocument` を受理したということなので `Completed`（`EventConsumer::finish` の契約どおり）。`StreamSource`
//!     や `DomSource` も同じで、文書を最後まで出した後の終了は `Stopped` ではない。
//!   - 実行が終わった後の書き込みは、終わり方で扱いを分ける。`end_document()` 後（呼び出し側のバグ）と消費者が
//!     拒否した後（拒否した呼び出しで既に報告済み）はエラー、全消費者が早期終了した場合は `Ok` で無視する。
//!     早期終了は異常ではないので、文書を最後まで書くアプリが誤った失敗を受け取らないようにするため。
//!   - API の境界では panic せず、呼び出し側の過ちも `Err` で返す（属性は報告できるよう `write_attribute` の
//!     戻り値を `Result<()>` にした）。ライブラリがアプリのプロセスを落とす理由はなく、`Err` で同じ情報が渡る。
//!     エラー種別は `Error::Internal`（「API 仕様が禁じる呼び出し」を含む）。ただし `Error::internal` の文面は
//!     xenolith のバグ報告を促すので、呼び出し側の過ち用に `Error::misuse` を設けた（同じ列挙子で、文面は
//!     渡した説明のみ）。公開メソッドが panic の代わりに返すのはこれ。
//!   - `XmlWriter` の内部メソッドは `EventRef` の名前（`start_element`、`characters`、`doctype` …）にし、引数も
//!     イベントそのものにした。`write_*` は StAX 風 API を writer が持っていた時代の名残。
//!     - 開始要素と属性は 1 メソッドに統合した。属性はイベントが要素と一緒に運ぶので、他の場所で属性を書く経路が
//!       なくなり、「開始タグがないのに属性」という状態が表現できなくなる（その検査とエラーも消えた）。
//!     - 名前用の再利用バッファ（`lexical` フィールド）は削除した。`mem::take` で取り出して戻す受け渡しが
//!       各所に必要で、しかも要素名は開始タグのスタックに積むため結局 1 回確保していた。いまは出力は
//!       `put_name` が接頭辞・`:`・局所名を順に書き（確保なし）、スタックに積む分だけ `lexical()` で組む。
//!       代償は接頭辞つきの名前でエンコーダ呼び出しが最大 3 回になること。終了タグの照合は `names()` で
//!       字句形を組まずに突き合わせる。
//!     - `EndElement` は、閉じる要素（writer が記録した名前）とイベントの名前が一致することを確かめ、違えば
//!       well-formedness エラー。記録した名前で黙って閉じると、イベントが述べていない文書を出力してしまうため。
//!   - `XmlWriter` は `EventConsumer` だけにし、`EventProducer` の実装はやめた。書いたイベントを後段に流す使い道は
//!     `WriterSource` と分けた今は残っておらず、複数の出力先に配るのも検査を前に置くのも `Dispatcher` の仕事。
//!   - `ValidatingWriter` は削除した（`Dispatcher` に validator を前置すれば同じ）。`Serializer` も削除した
//!     （`DomSource` + `XmlWriter`）。名前空間の補完とインデントは失われたので、必要ならイベント列を整える
//!     ユーティリティの消費者として作り直す。
//! - `XmlWriter` の XML 宣言は `with_declaration` の設定にし、`StartDocument` で書く。XML 宣言を運ぶイベントがない
//!   （パーサも読み飛ばす）ため、呼び出しではなく writer の設定に置いた。
//!   - 設定は「宣言を書くか」（`with_declaration(bool)`）、`standalone`（`with_standalone(Option<bool>)`）、「宣言の
//!     直後に書くもの」（`with_declaration_line_break(Option<LineBreak>)`）の 3 つに分ける。以前は `with_declaration(Option<
//!     bool>)` 1 つで、`Some` を渡したかどうかが「宣言を書くか」を兼ねており、呼び出し側から意味が読めなかった。
//!   - `standalone` は 3 値のまま（書かない・`yes`・`no`）。省略と `"no"` は §2.9 上同じ意味だが、`"no"` と明示して
//!     書く形を残す。
//!   - 宣言の後の改行は、宣言を書く `XmlWriter` の責務。ほかのトップレベルの改行（DOCTYPE、コメント、PI、ルート
//!     要素の後）は、後で作る整形用の transformer の責務とし、writer は受け取ったものをそのまま書く。
//!   - `LineBreak` は「CR・CRLF・LF・空白」の 4 値で、列挙型としての既定は LF。整形用の transformer でも使うので
//!     `io::write` に置く。「何も書かない」は列挙値に含めず `Option` の `None` で表す（`LineBreak` は書く文字の
//!     種類であり、「書かない」はその不在だから）。`with_declaration_line_break` の既定は `None` で、宣言を
//!     書く出力は従来どおり宣言の直後に次のマークアップが続く。入力の宣言の後の空白はイベントとして流れるので、
//!     `StreamSource` から `XmlWriter` へそのまま流せば入力の改行が保たれる。改行を付け足すと二重になり得るので、
//!     それを整えるのは整形用の transformer の役目。
//! - パーサの設定は `ParserConfig` をルートとする入れ子の構造体にまとめる。
//!   - `extensions`（XML Base、`xml:id`）、`limits`（`tokens`/`entities`/`document`）、`text_fragment_len`。
//!   - 構造体は「どこで使われるか」で分ける: `TokenLimits` はスキャナ、`EntityLimits` は実体スタック、
//!     `DocumentLimits` と `Extensions` はパーサ本体。ただし設定の入口は `ParserConfig` 一つ（`set_config`/
//!     `with_config`）にし、以前の `Bounds`/`Limits` の別々の設定経路（`with_bounds`、`with_document` の引数）は
//!     なくした。アプリケーションがスキャナや実体スタックを個別に設定することはまずないため。
//!   - `text_fragment_len` は何も拒否しないので制限ではなく、`limits` の外、トップレベルに置く。
//!   - 各構造体は `Copy` と `Default` を持つデータで `#[non_exhaustive]`。利用側は `default()` から始めてフィールドを
//!     書き換える（`config.limits.entities.max_expansions = Some(..)`）。入れ子で長くなるフィールドごとの `with_*` は
//!     置かない。プリセットは `Limits::unlimited()` などの `unlimited()` と `Extensions::none()` だけ。
//!   - XML Base と `xml:id` は実行時の設定だけで、Cargo feature では切り替えない。
//! - `xml:id` を無効にしたら `xml:id` 属性は普通の属性として扱う（DTD が `ID` と宣言していればその理由で ID）。xml:id
//!   勧告では ID 型になるのは xml:id 処理の結果だから。
//!   - `DomBuilder` はパーサの設定を知らない（イベントを受けるだけで、パーサ以外のソースからも組み立てる）ので、自前の
//!     `with_xml_id(bool)`（既定は有効）を持つ。パーサ側で切ったら利用側がこちらも切る。xml:id を検査するかを検証側の
//!     方針とした `ValidatorSet::checking_xml_id` と同じ考え方。
//! - `DomBuilder` も、イベント列が文書を成さないときは panic せずエラーにする（`XmlWriter` と同じ方針）。
//!   - `EndElement` は開いている要素がなければ、あるいはイベントの名前が最内の要素と違えば well-formedness エラー。
//!     以前は無条件に pop していたため、終了が多い列では土台の document ノードまで外れて panic していた。
//!   - DOM 例外で実行を止めるときは、`DomException` をそのまま包む `Error::Dom` を追加した（`Error::dom`）。
//!     `Error::internal` ではバグ報告を促す文面になり、`Error::well_formedness` では例外コードが文面に溶けて
//!     失われる。`Error` しか見えない呼び出し側からも `exception.code()` で判断できるようにした。
//!     `#[source]` にもしてあるので downcast でも辿れる。
//!     - `From<DomException> for Error` も入れた。`?` が変換するので、DOM 操作の結果を包み直す関数は要らない。
//!     - エラーの位置は `consume` の出口で処理中のイベントのものを `or_at` で付ける。DOM にはノードを渡すだけで
//!       位置を渡さないので、位置を知っているのはイベントだけ。そのため各イベントの処理はメソッドに切り出した
//!       （`?` が match アームから関数ごと抜けてしまい、出口の処理を飛ばすため）。
//!     - `failure` フィールドと `into_document` の `Result` は削除した。例外は実行のエラーとして伝わるので、
//!       同じ事実が 2 経路で流れていたことになる。しかも `failure` に入るのは DOM 例外だけで、パースエラーでは
//!       `Ok`（途中までの木）が返っていたので、「木が完全である」という約束にもなっていなかった。
//!       `into_document` は `XmlWriter::into_inner` と同じく、あるものをそのまま返す。
//!   - `StartDocument` で組み立て状態をリセットする。文書の開始は `Dispatcher` と同じく新しい実行だから。
//!     - リセットは `Document` ごと作り直す（開いているノード、捕捉した DTD、記録した基底 URI、止めた例外も含めて）。
//!       ノードを残すと、新しい実行のルート要素が「2 つ目のルート」として DOM に拒否され、リセットしても何もできない
//!       状態になる。1 回の実行が 1 つの文書を作る、とした。
//!     - よって `into_document` が返すのは最後の実行の文書。前の文書が必要なら次の実行の前に取り出す（`into_document`
//!       は `self` を消費するので、もともとその使い方）。`XmlWriter` は書いたバイトを取り消せないので残るが、DOM は
//!       捨てられるという違い。
//! - 内部サブセットから参照された外部パラメータ実体の置換テキストを「外部」として扱うこと（XML 1.0 §2.9）。
//!   - `DtdAssembly` がその置換テキストの範囲（external regions）を記録し、パーサは内部サブセットの境界に加えて
//!     それも外部とみなす。そこで宣言された実体と属性リストは standalone 文書が依存できないものとして印が付き、
//!     宣言内の PE 参照や条件付きセクションなど外部サブセットの文法で読まれる。
//!   - 境界 1 つ（`internal_len`）では表せないので、範囲の一覧を持つことにした。内部 PE の展開で位置が動くたびに、
//!     `internal_len` と同じく範囲も動かす。これらはバッファの出自として `Layout`（crate 内部）にまとめた。
//!   - `parse_dtd` はこの `Layout` を受け取るので crate 内部に下げた。外部から DTD を段階的に読む入口は
//!     `DtdAssembly`、単独のサブセットは `parse_subset`。
//! - 宣言が PE の境界をまたがないこと（WFC: PE Between Declarations、VC: Proper Declaration/PE Nesting）の検査に使う
//!   PE の範囲も `Layout` に持ち、パスをまたいで残す。
//!   - 以前はパスごとに捨てていたので、外部 PE の範囲と、前のパスで展開した内部 PE の範囲は検査されなかった。
//!   - PE の中の PE で範囲が入れ子になるので、位置が属する範囲は最も内側のものとする。
//!   - INCLUDE セクションの中の宣言にも同じ検査をする。
//! - `Layout` はバッファの各部分（piece）を出自とともに持つ: 内部サブセット、外部サブセット、外部 PE、内部 PE。
//!   - 文書・リソースから読んだ piece は開始位置（`Location`）を持つ。外部か否か、宣言の基底 URI、エラーの行・桁は
//!     すべて「その位置を含む最も内側の piece」から求める。
//!   - 行・桁は、piece の開始位置から対象位置まで文字を数えて求める。途中に差し込まれた子 piece は、置き換えた参照
//!     （`%name;`）の文字数だけ桁を進めて飛ばす。内部 PE の置換テキストには自分の位置がないので、その中の位置は参照の
//!     位置として報告する。
//!   - そのため `DtdAssembly` は各テキストを受け取るときにその開始位置を受け取る（`with_internal_subset`、
//!     `add_external_subset`、`provide_parameter_entity`）。エラー位置はここから決まるので、`advance`/`complete` の
//!     `base` 引数はなくした。
//! - 外部実体（一般・パラメータ・解析対象外）の相対システム識別子は、その宣言が書かれたリソースを基準に解決する（XML
//!   1.0 §4.2.2）。参照された場所ではない。
//!   - 基準は宣言の性質なので、モデルの `GeneralEntity::External`/`Unparsed` と `ParameterEntity::External` に
//!     `base` として持たせた（Infoset の declaration base URI に当たる）。DTD パーサが宣言の位置の piece から求める。
//!   - 外部 PE は `ExternalPe::base` で、一般実体は宣言の `base` で、要求を出す側が基準に使う。`base` がなければ
//!     文書の基底 URI を使う。
//! - 実体値リテラル中の外部 PE は、リテラルのデータとして取り込む（§4.4.5）。前後に空白を付けず、引用符は文字参照に
//!   置き換えて差し込み、リテラルを閉じないようにする。差し込んだ後は他のリテラル内容と同じく読み直す。
//! - トークン型属性の既定値に実体参照がある場合、既定値を補うときに参照を展開してから、もう一度トークン正規化する。
//!   DTD を読む時点では参照が未展開なので、そこでの正規化だけでは足りない。
//!
//! ## XInclude
//!
//! - 木の後処理ではなくパイプラインの一段（transformer）として実装した。取り込んだ内容は木を作らずそのまま下流へ
//!   流れるので、`DomBuilder` でも `XmlWriter` でも検証器でも同じ形で使える。旧 `xenolith-xinclude` クレートは
//!   DOM を作ってから差し替える形で、書き出しだけが目的でも木を必要としていた。
//! - 取得できなかった（resource error）ときだけ `xi:fallback` を使う。整形式でない XML、復号できないバイト列など
//!   「取得はできた後の失敗」は致命的エラーで、fallback は代わりにならない（XInclude 1.0 §4.3 が明記している）。
//!   - 失敗を報告する場所は `xi:include` の終了タグ。開始タグの時点では fallback があるか分からないので、
//!     エラーを frame に持たせて終了タグまで運ぶ。
//! - `xi:include` の中身は検査しない。§3.1 が「テキスト・PI・コメント・XInclude 名前空間でない要素・子要素の子孫は
//!   この仕様が制約せず、プロセッサは無視する」と明記している。`<xi:include><p><xi:include/></p></xi:include>` の
//!   内側も誤りではない（子ではないので）。致命なのは**子**に `xi:fallback` が 2 つ以上、`xi:include`、その他の
//!   XInclude 要素が来る場合（§3.1）と、`xi:fallback` が `xi:include` の直接の子以外に現れる場合（§3.2）。
//!   - 節番号を取り違えていた: この 2 つは §3.1 / §3.2 で、§4.3 は取得失敗時の fallback の使い方の節。
//!   - `encoding` を `parse="xml"` に書いた場合と、`xi:include` / `xi:fallback` の外に現れた未知の XInclude 要素は
//!     仕様が制約していない（前者は「効果がない」だけ）。報告はするが、仕様より厳しいことをドキュメントに明示する。
//!   - 公開ドキュメントには準拠する仕様（XInclude 1.0 Second Edition）へのリンクと、上の「仕様より厳しい 2 点」
//!     だけを書く。どの節が何を禁じているかは仕様を読めば分かることなので、検査項目の一覧は置かない。
//! - **`XIncludeTransformer` はサブパイプ。** 上流からのイベントを 1) `with_max_errors(Some(0))` の
//!   `XIncludeSchema`、2) 処理本体の `XIncludeProcess`、3) `RootElementConstraints` の順に通す。公開型は設定と
//!   配線だけを持ち、`xi:include` の処理は非公開の `XIncludeProcess` が持つ。
//!   - 語彙の検査を Transformer 自身が持つので、手で配線する利用者が前段を置き忘れて構造違反が黙って処理されることが
//!     なくなった。ファサードの前段の `ValidatorSet` も不要になった。
//!   - 実行の終わり（`finish`）と新しい文書の始まり（`StartDocument`）を知るのは公開型だけ。`XIncludeProcess` は
//!     入れ子の lane からも `finish` を受けるが、それは取り込んだ文書の終わりで実行の終わりではないので無視する。
//!     以前は「開いている取り込みがないとき」だけ後続へ伝えていたため、取り込みの途中で失敗した実行は後続に
//!     `Failed` ではなく（`Dispatcher` の drop による）`Abandoned` として届き、次の文書でも状態が初期化されなかった。
//!   - 3 段目を公開型に置けないのは、2 段目が 1 つの入力から複数のイベントを出し、その出力先を自分で持つ必要が
//!     あるため（下の `RootElementConstraints` の項を参照）。3 段目は `XIncludeProcess` の送出経路に置く。
//!     - 出力先を呼び出しごとに貸す形（「3 段目 + 後続」の送出先と「処理本体 + 送出先」の束の 2 型を足す）なら
//!       公開型に置けるが、採らない。どちらも意味を適切に定義できない型で、構成が見えること以上の得がない。
//! - **語彙（構造）の検査は処理本体に持たせず、`XIncludeSchema` に分けて前段に置く。** §3.1 / §3.2 が
//!   `xi:include` と `xi:fallback` について言うこと（`parse` の値、`href` のフラグメント、`accept` 系の文字範囲、
//!   fallback の位置と個数、子に置ける要素、未知の XInclude 要素）はすべてスキーマ側で、処理本体は「来たものは
//!   妥当」と仮定する。処理本体に残るのは、取得結果に依存するものと結果に対する規則だけ。
//!   - 致命にするのは配線で行う。`ValidatorSet::with_max_errors(Some(0))` を付けると 1 件目の妥当性エラーで
//!     `Err` になり、`Dispatcher` がそのイベントを止めるので、**違反イベントは Transformer に届かない**（§2 の「resource
//!     error 以外では処理を止める」を満たす）。エラー種別は `Error::XInclude` ではなく `Error::Validity` になる。
//!   - 代償: §3.2 の「無視される `xi:fallback` の中の誤りを fatal error として報告してはならない」を満たせない。
//!     前段の検証器は取得が成功するかを知る前に判断するため、使われずに捨てられる fallback の中の誤りでも止まる。
//!     無視されるか否かは取得後にしか分からないので、静的な検証器と両立しない。検出漏れなしを採った。
//!   - 処理本体の `consume()` の先頭に内包する形は採れない。取り込んだ文書のイベントは `xi:include` の開始タグと
//!     終了タグの間に流れるので、内包した検証器から見ると**取得した文書のルート要素が `xi:include` の子**に見え、
//!     §3.1 の「子に `xi:include` を置けない」に誤って当たる。文書境界（`StartDocument`）は処理本体が飲み込むので、
//!     検証器が区別する手段もない。処理本体より前に置くしかない。サブパイプの 1 段目はこれを満たす: 取り込んだ
//!     文書のイベントは入れ子の lane から処理本体へ直接届き、1 段目は上流のイベントしか見ない。
//!   - 取り込んだ文書の分は処理本体が配線する（入れ子の lane に同じスキーマと `with_max_errors(Some(0))`）。
//!     外側の文書の分はサブパイプの 1 段目。
//!   - したがって `XIncludeSchema` は公開する（`DtdSchema` と同じ扱い）。検証器そのものは非公開で、スキーマが
//!     生成する。名前を `Schema` ではなく `XIncludeSchema` にしたのは、`event::validate::Schema`（トレイト）と
//!     同名だと両方を import する側が別名を必要とするため。
//! - base / language fixup（§4.5.5、§4.5.6）は既定 ON で個別に OFF（`with_xml_base` / `with_xml_lang`）。取り込み
//!   点と異なる基底・言語を持つ要素は、その場に書いたなら `xml:base` / `xml:lang` を書かねば同じ意味にならない。
//!   仕様も切ることを認めている（§4.5.5 の "may (at user option) suppress"）。
//!   - 対象は**取得した文書の最上位要素だけ**。その下の要素は最上位から継承するので書く必要がなく、書くとその要素
//!     自身の `xml:base` を上書きしてしまう。スコープに「最上位要素がまだ来ていない」印を持たせ、1 回で下ろす。
//!   - 要素が自分で書いた `xml:base` / `xml:lang` は**残さず置き換える**（両節の "If an xml:base attribute
//!     information item is already present, it is replaced by the new attribute"）。相対値を残すと、結果の中では
//!     取り込み先の親の基底に対して解決され、別の場所を指す。置き換えるのは同名のものだけで、`xml:id` や
//!     `xml:space`、fixup が触れない側の属性はそのまま残す。
//!   - 言語の比較は大文字小文字を無視する（§4.5.6 の "taking case-insensitivity into account per [IETF RFC 3066]"）。
//!     `xml:lang=""` は「言語なし」なので、要素に言語がなく取り込み点にある場合は空値を書いて打ち消す。
//!   - 厳密には比較相手は include parent（`xi:include` の親）だが、記録しているのは `xi:include` 自身の実効値。
//!     ずれるのは `xi:include` 自身が `xml:base` / `xml:lang` を持つ場合だけで、include parent の値を得るには
//!     開いている全要素の基底と言語を保持する必要があるため、そこまではしない。
//! - §4.5 の「ルート要素の位置に置けるもの」の検査は `RootElementConstraints` として処理本体の送出経路に置く。
//!   `xi:include` がルート要素だった場合、置き換えとして許されるのは「コメント・PI と要素ちょうど 1 つ」、つまり
//!   XML 文書の中身の形だけ。`parse="text"` や 2 要素を持つ fallback はこれを壊す。
//!   - **結果に対する規則なので前段の検証器には書けない**（ソース文書を見ても取り込み先の形は分からない）。
//!     判定は「下流へ出るイベントのうち、どの要素も開いていない位置に何が来たか」だけで済み、ソース文書はそこに
//!     要素 1 つと空白・コメント・PI しか置けないので、それ以外は取り込みが持ち込んだもの。
//!   - `StrictXmlConstraints` を下流に置いても同じ検査ができる（あれも「ルート要素は 1 つ」「外側のテキストは空白
//!     だけ」を見る）が、開いた要素の名前を `String` のスタックで持つので要素ごとに確保が起きる。上流と入れ子の
//!     lane が構造を検証済みの分を二重に見ることにもなるので、`usize` 2 つの軽い検査を選んだ。
//!   - 処理本体が自分の `dispatch` に自分のフィールドを登録することはできない（自己参照）。送出の途中で通す形に
//!     した。`EventConsumer` にしているのは、§4.5 が fatal error なので止める必要があり、`Validator`（集めて続行）
//!     の契約に合わないため。
//!   - ルート要素が 0 個になる場合（空 fallback がルートを消した場合）も致命にする。§4.5 の引用が "and one
//!     element" と言っており、XML 1.0 の `[1] document ::= prolog element Misc*` でも整形式でない。外側の文書の
//!     `EndDocument` は処理本体を通って届く（取り込み中のものは飲み込まれる）ので、そこで数えられる。以前は
//!     「数えられない」として下流に任せていたが、誤りだった。`EndDocument` は位置を持たないので、位置は不明になる。
//! - `Limits` の既定は深さ 8 / 総数 1000。部品から組み立てた文書が必要とする範囲より十分に広く、資源を
//!   使い尽くすには十分に狭い。上限なしは `Limits::unlimited()` で明示的に選ぶ。
//! - `xpointer` は `xenolith::xpointer` の `XPointerFilter` で選ぶ。取り込んだリソースを読む入れ子のレーンで、
//!   検証器（strict と `XIncludeSchema`）の後、`XIncludeProcess` の前に置く。リソース全体を検査し、選んだ部分
//!   だけを取り込む。
//!   - 解析できないポインタ、何も指さないポインタ、流しながら評価できないポインタは、どれもリソースエラー（§4.2
//!     "An error in the XPointer is a resource error"）。解析エラーは取得の前に分かるので、何も取得しない。
//!   - リソースエラーに読み替えるのは、その取り込みの filter が返した `Error::XPointer` だけ。その時点ではリソース
//!     の何も下流へ流れていない（filter は選んだ要素の開始から流し、失敗は開始と終了で返す）ので、fallback を
//!     そのまま差し込める。
//!   - fallback のない `xi:include` のリソースエラーは致命なので、スコープを閉じるときに `Error::XPointer` を
//!     `Error::XInclude` に変えて返す。`Error::XPointer` のままだと、外側の取り込みが自分のポインタの失敗と
//!     取り違え、外側の fallback に置き換えてしまう。
//!   - ループ検査の鍵は §4.2.7 どおり「include location と `xpointer` の組」。同じリソースの別の部分はループでは
//!     ない。
//!   - 検証器は `xpointer` を妥当と扱う（§3.1 が認めている）。値の誤りは文書の誤りではなく §4.2 のリソースエラー。
//!   - XPointer を実装するまでは、`xpointer` のある `xi:include` を一律にリソースエラーにしていた（2026-09-27 から）。
//!     部分を求めた文書にリソース全体を黙って返すのは、読めないことより悪い（利用者が気づけない上に、実装後に出力が
//!     変わる）ため。当初は致命エラーで拒否し、2026-09-28 にリソースエラーへ改めた。
//! - **`href` のない `xi:include`（同一文書の部分取り込み）は取り込まず、リソースエラーにする。** §3.1 は `href` の
//!   省略を `href=""`、すなわち処理中の文書自身への参照と定めているが、これはイベントパイプラインでは扱えない。
//!   XPointer を実装した後もこのまま（TODO ではなく設計上の帰結）。§4.1 が "An implementation may choose to treat
//!   any or all absences of a value for the href attribute as resource errors" と認めているのでリソースエラーとし
//!   （当初は致命エラーだった）、同節の "should document the conditions" に従いモジュールドキュメントに書く。
//!   - 理由: Transformer の手元に「現在の文書」がない。イベントはコールバック 1 回の借用で、流したら忘れる。
//!     ポインタの指す先は `xi:include` より後ろにあり得る（前方参照）ので、その場では答えられず、前にあるものは
//!     既に下流へ流れている。短縮ポインタが要する ID は DTD か `xml:id` から来るので、文書を読み終わるまで確定
//!     しない。
//!   - 採らなかった案: 原文書を全部バッファする（保持量が文書サイズになり、前方参照のために文書末尾まで下流へ
//!     何も流せなくなる）。入力を 2 回読む（`StreamSource<R: Read>` は再読み込みを保証しない）。
//!   - 必要になったら、木の上で動く別の手段（DOM を構築してから展開するパス）を用意する。旧 `xenolith-xinclude`
//!     が DOM 後処理だったのは、この制約が理由だったと読める。
//!   - 一方 `href` のある `xpointer`（外部リソースの部分取り込み）はこの設計でも実装でき（実装した）、しかも**XPointer 自身を
//!     Filter（`XPointerFilter`）** にできる。選択した部分木の中のイベントだけを通す消費者を、取得したリソースを
//!     読む入れ子のパイプラインに挟めばよい。位置指定（`element(/1/2)`）は深さと出現位置を数えるだけ、短縮
//!     ポインタ（ID）は `xml:id` なら開始タグの属性で判定でき、DTD 宣言の ID 型も `Doctype` イベントが運ぶ `Dtd`
//!     から分かるので、いずれも木を作らずに流しながら選べる。何も選ばなければ §4.2 の「An error in the XPointer
//!     is a resource error」に当たるので、そのまま fallback に落ちる。
//!     - 流しながら選べないのは、ポインタ部分列（`element(a/1) element(b/2)` のように候補を順に試す形）である。
//!       前の候補が失敗したと分かるのは文書の終わりなので、バッファか 2 パスが必要になる。`xpointer()` scheme
//!       （XPath ベース）も対象外（ROADMAP）。
//!   - 検証器は `href` のない `xi:include` を妥当と扱う（§3.1 が認めている）。文書の誤りではなく、この実装が
//!     carry out できないだけなので、扱うのは Transformer の役目。
//! - §4.2.7 のループ検査が比べるのは、**実際にリソースを処理しているスコープ**（`InclusionInProcessing`）だけ。
//!   fallback 中のスコープのリソースは取得できておらず処理されていないので、fallback の中で同じ URI を取り込むのは
//!   ループではない（「部分が選べなければ全体を」という書き方）。以前は「エラーを持たないスコープ」で絞っていた
//!   が、fallback に入るとエラーを消すので、そのスコープが比較対象に入っていた。
//! - `encoding` 属性がこのビルドで復号できない名前なら、リソースエラーにする（§4.3 の "the resource is in an
//!   unsupported encoding"）。以前は致命エラーだった。URI の構文エラーは §3.1 の "should be reported as a fatal
//!   error" に従い致命エラーのまま。
//! - MUST のうち実装していないもの: §4.5 の未解析実体・記法の統合（取り込んだ文書の `DOCTYPE` を結果に持ち込ま
//!   ないので、同名で異なる宣言の致命エラーも報告できない）。コードのコメントに仕様の原文とともに記録した。
//! - 実装した検査には、根拠にした仕様の原文を引用してコメントに残す。節番号だけだと版と節の対応を取り違えても
//!   気付けない（実際に §3.1／§3.2 を §4.3 と誤って書いていた）。
//! - `let` chains は使わない。MSRV 1.85 では不安定（Rust 1.88 以降の機能）で、`cargo +1.85 build` が落ちる。
//!
//! ## XPointer
//!
//! - ポインタは一度だけ解析して不変の `XPointer` にし、複数の `XPointerFilter` で共有する（`XPointer::parse` と
//!   `XPointerFilter::new(&pointer)`）。filter はポインタを借用する。実行ごとの状態は filter が持つ selector だけが
//!   持ち、`StartDocument` で作り直す。
//!   - 元の文字列は `as_str()` と `Debug` で参照できる。`Debug` は解析結果の内部ではなく、書かれたポインタと位置を
//!     示す。
//! - scheme ごとに多態化する（scheme 名ごとの enum にしない）。後から scheme を順に足せるようにするため。
//!   - 非公開のトレイト 2 つ: `SchemeData`（scheme が解析した part のデータ。不変で共有）と `SchemeSelector`（1 回の
//!     実行での状態）。`SchemeData::selector` が selector を作る（旧名 `SchemeSession`）。
//!   - selector の選び方は 2 通り。ストリーミングでは `filter` がイベントごとに状態を更新し、そのイベントを通すか
//!     （`true`）落とすか（`false`）を返す。文書全体を見ないと決められない scheme（XSLT のように内部で DOM を
//!     作るもの）は、`filter` では何も通さずに読んだものを保持し、`drain` で選んだものをカーソル
//!     （`Option<Box<dyn EventCursor>>`）として返す。filter は `EndDocument` を selector に渡した後に `drain` を
//!     呼び、カーソルの `StartDocument` と `EndDocument` を除いて中継してから、`EndDocument` を流す。`drain` の
//!     既定は `None`（ストリーミングの selector）。
//!   - `drain` が `Iterator` ではなくカーソルを返す理由: `EventRef` はイベントを出したもの（たとえば `DomSource` が
//!     属性の一覧を置くフィールド）を借用するので、`Iterator` の要素にできない。所有の `Event` の `Iterator` なら
//!     作れるが、イベントごとに複製が要る。カーソルなら selector が持つ木を借用したまま、複製せずに列挙できる。
//!     名前は `flush`（consumer に送る形）から改めた。
//!   - 何かを指したかは filter が流したイベントの有無で判定する（`identified` は置かない）。`drain` がカーソルを
//!     返すので、保持型の selector の分も filter が数えられる。何かを指してもイベントが出ない scheme（`xpointer()`
//!     の point、XInclude §4.2.4）を足すときは、判定を selector に問う形に戻す。
//!   - filter は枠（`StartDocument`、`EndDocument`、`Doctype`）とエラーだけを受け持ち、選択は scheme に任せる。
//!     `Doctype` も selector に渡す（`element()` は DTD の ID 宣言を読む）が、流すかは filter の設定で決める。
//!   - scheme 名から `SchemeData` を作るのは `parse_scheme_data` の 1 か所。未対応の scheme、`xmlns()`、データが
//!     構文に合わない part は保持しない（何も指さない）。`element()` は `xpointer/element.rs`。
//!   - 短縮ポインタは `element(NCName)` と同じ part として保持する（Framework §3.2 が同じ要素を指すと定める）。
//!   - 名前は `compile` ではなく `parse`。解析して簡単な照合手順を作るだけなので、関数合成までする XPath の
//!     `compile` と区別する。`FromStr` も実装する。
//!   - `parse` はポインタの先頭の `Location` を受け取り、`XPointer` が保持する。構文エラーはその位置から文字を
//!     数えて誤りの文字に、filter のエラーはポインタに位置づける。位置は
//!     値の文字を数えたものなので、参照を含まずに書かれたポインタでは文書の位置と一致する。
//!   - 単独の文字列として解析するとき（`FromStr`、doc の例）は `Location::new()`（1 行 1 桁）から数える。
//!     `Location::unknown()` では位置が数えられず、何文字目の誤りかを示せないため。
//! - `XPointerFilter` は Filter（イベントを選ぶだけの中段）。選んだ要素とその部分木を `StartDocument` と
//!   `EndDocument` で囲んで流す。出力は文書ではなく文書断片の形で、strict XML の保証はしない。
//! - `Doctype` を流すかは filter ごとの設定（`with_doctype`、既定は流さない）。ID の宣言を読むので、流さなくても
//!   読む。
//! - 何も指さなければ `EndDocument` で `Err(Error::XPointer)` を返す。Framework §3.2・§3.3 がそれをエラーと定めて
//!   いるので、XPointer の処理系である filter が報告する。XInclude が届いたものを数えて判定する案は採らなかった
//!   （XInclude 以外で filter を使う利用者にも伝わらない）。
//! - 評価できる part（対応する scheme の part）が複数あるポインタは、Framework §3.3 どおり前から順に試した結果に
//!   なるよう、すべての part を同時に評価する（2026-10-03。それまでは「未対応」として拒否していた）。
//!   - 2 階層に分ける。filter（`XPointerFilter`）が part ごとの `SchemeSelector`（`Candidate`）をまとめ、保留と
//!     破棄を一手に受け持つ。各 scheme の selector に同じ保留の処理を書かせないため。一時は中間の具象の
//!     `XPointerSelector` に持たせたが、filter の外に見せる相手がいないので filter に移した。
//!   - 先頭の part が選んだものはその場で流す。先頭が何かを選べば結果は確定するからで、その時点で後ろの part を
//!     保留ごと破棄する。2 番目以降の part が選んだものは、filter が所有の `Event` で保留する。ある part が選び
//!     始めた時点で、それより後ろの part を保留ごと破棄する（前の part で、まだ何も選んでいないものは残す）。
//!     `EndDocument` で、残っている part のうち何かを選んだ最も前のものの保留と、その part 自身の `drain` を流す。
//!   - 「保留」（pending）と呼ぶのは、前の part の結果を待って渡すのを控えているから。以前の名前は held で、何を
//!     なぜ持っているのかが読み取れなかった。
//!   - 保留は所有の `Event` の列にする（DOM にしない）。`DomSource` は `xml:lang` などの有効値を復元しないので、
//!     XInclude の言語の fixup が変わってしまうため。保留した列は、`EndDocument` で `drain` のカーソル
//!     より先に流す。
//!   - 保留の大きさは、2 番目以降の part が選んだ部分木の大きさ。前の part が早く選べば、すぐに捨てられる。
//!   - 保留の量には上限を置く（`XPointerFilter::with_max_pending_chars`、XInclude からは
//!     `Limits::max_pending_chars`、既定 16 Mi 文字、超えたら `Error::Limit`）。ほかの上限と同じく既定で有限にし、
//!     `None` で外す。
//!     - 数えるのは、保留するイベントが持つ文字列の文字数（要素名、属性の名前と値、テキスト、CDATA、コメント、
//!       PI のターゲットとデータ）。イベント数よりメモリの量に近いため。イベントごとの固定の大きさは数えないので
//!       目安であり、小さな要素が多数並ぶと実際の使用量は大きくなる。その旨を doc に書いた。
//!     - 既定値は、CDATA 1 つの上限（16 MiB）と同じ程度。実体展開の生成文字数の上限（64 Mi 文字）より小さく、
//!       普通の部分取り込みでは届かない。
//!     - 先頭の part が選んだものはその場で流すので数えない。
//!   - 各 `Candidate` が自分の列を持つのは、保留を持つのが常に高々 1 つ（何かを選んだ最も前の part）だから。
//!     filter に共有の列を置いても保留する量は減らず、誰のイベントかが分かりにくくなるだけ（コメントに記載）。
//!   - `drain` 型の selector（自分で保持するもの）は `filter` で何も選ばないので、何かを選んだかは `EndDocument`
//!     で `drain` が `Some` を返すかで判断する（何も選ばなければ `None` を返す約束）。
//! - 評価できる part が 1 つもないポインタ（未対応の scheme だけ、など）は、`StartDocument` で拒否する。何も
//!   指せないことが最初から分かるため。
//! - part ごとの解析結果を `Result` で持ち、エラーは 1 つを選ぶ。未対応の scheme（と `xmlns()`）の part は除いて
//!   数え、対応する scheme の part が 1 つもなければ「対応する scheme の part がない」とする。対応する scheme の
//!   part があってもすべてデータが構文に合わないなら、先頭の part のエラー（データの中の誤りの文字の位置）を使う。
//!   構文に合う part が 1 つでもあれば、合わない part は仕様どおり何も指さないものとして無視する。
//!   - 構文に合わない part のエラーは `XPointer::errors()` で順に読める。選択には使われない part でも、利用者が
//!     書き誤りに気づけるようにするため。未対応の scheme の part は仕様どおり読み飛ばすもので、エラーではないので
//!     含めない。`XPointer` を複製できるよう、エラーは `Arc<Error>` で保持する（`Error` は `Clone` でない）。
//! - Framework の規定に合わせて、ポインタ全体の構文エラーは `parse` の `Err`、未対応の scheme の part は読み飛ばす
//!   （§3.3）。`element()` のデータがその構文に合わない part は何も指さない（`element()` scheme の規定）ので、
//!   `parse` では拒否しない。`xmlns()` は受け付けるが何も指さない。
//! - ID は開始タグの時点で判定する。`xml:id` と、`Doctype` の DTD で `ID` 型と宣言された属性が対象。`xml:id` の
//!   値は ID として正規化して比べる（パーサが正規化していない場合があるため）。
//!
//! ## XPath
//!
//! - 外していた `xenolith-xdm` と `xenolith-xpath` を core の `xpath` モジュールに移す（2026-10-04）。データモデル
//!   （XDM）は非公開のサブモジュール `xpath::model` にする。外したクレートはまだ消していない。
//! - XPointer と同じく、式は一度だけ解析して不変の `XPath` にする（`XPath::parse(&str, Location, Limits)` と `FromStr`）。
//!   旧クレートの Java 風の「環境の `XPath`」と「式の `XPathExpression`」の 2 つには分けない。
//!   - `parse` は式の先頭の `Location` を受け取る。構文エラーはそこから文字を数えて誤りの文字に、評価のエラーは
//!     式の先頭に位置づける。文書の中に書かれた式（XSLT の属性、将来の `xpointer()`）のエラーに位置を付けるため。
//! - 評価は `XPath::evaluate(&Document, NodeId)`。文脈ノードを受け取るので、相対パスを任意のノードから評価できる。
//!   ほかの文書のノードは `Err` にする（API の境界で panic しない）。
//!   - 呼ぶたびにデータモデルを作る。文書順の索引は最初に順序が要るときに文書全体について作る（並べ替えのない式
//!     や、結果の `string` では作らない）。同じ文書に多くの式を当てるときの費用は、文書ごとの準備を共有する
//!     Selector を作るときに扱う。
//! - 結果は `XPathResult` の 4 値（`NodeSet`、`Boolean`、`Number`、`String`）。XPath 1.0 の型が 4 つだから。Java の
//!   `XPathConstants.NODE` は「node-set の先頭を 1 つ取り出す」という取り出し方の指定で、型ではないので値にしない。
//!   - 名前は DOM Level 3 XPath の `XPathResult` に合わせる。`Value` は一般的すぎて、`use` したときにほかの
//!     クレートの `Value` と紛れ、XPath の結果だと読めない。仕様の用語の object は、Rust ではトレイトオブジェクト
//!     などを連想させる。
//!   - 取り出し方の指定は値ではなくメソッドにする。`node()` は node-set の先頭（`Option<&Node>`）、`boolean()` と
//!     `string(&Document)` は XPath の `boolean()` と `string()` の変換。`string` が文書を受け取るのは、node-set が
//!     `NodeId` しか持たず、文字列値を読むのに文書が要るため。ほかの文書のノードは `Err` にする。
//! - node-set の要素は `Node`（`Dom(NodeId)` と `Namespace { element, prefix }`）。名前空間ノードには DOM の
//!   `NodeId` がないため（Java では DOM Level 3 XPath の `XPathNamespace`、nodeType 13 にあたる）。テキストノード
//!   は、連続するテキストと CDATA セクションの先頭の DOM ノードで表す。
//! - 名前空間の束縛は今は受け取らない。束縛を受け取る版は後で `_ns` の名前で別に作る（2026-10-04）。それまでは
//!   `xml` だけが束縛済みで、ほかの接頭辞は評価で「束縛されていない」エラーになる。変数と拡張関数もまだ渡せず、
//!   参照すればエラーになる。
//! - 評価器は旧クレートの木をたどるインタプリタをそのまま移した。関数合成によるコンパイルには、後で内部だけを
//!   置き換える。
//! - `XPath` の `Display` は解析した木から書き戻す（2026-10-05）。`{}` は省略形（`a`、`@x`、`.`、`..`、`//`）を
//!   使える限り使い、括弧も解析し直して同じ木になる分だけにする。`{:#}` は省略しない形で、二項演算をすべて括弧で
//!   囲む。元の文字列は保持しない。
//!   - 一度は書かれたとおりの文字列を保持して出す形にしたが、解析済みの木から書き戻す形に改めた。空白や数値の
//!     書き方（`.5` は `0.5`）は再現しないが、式が正規化された形で読める。
//!   - 省略しない形は `{:#}` に残す。テストで省略形の展開と優先順位を確かめるのに要り、利用者にも式がどう解釈
//!     されたかを示せるため。印字のコードは 1 つで、省略するかどうかを切り替えるだけにする（2 つ持つと、括弧と
//!     字句の注意事項を 2 か所で保守することになる）。メソッドを 2 つ公開する形は、`format!` で使えないので採らない。
//!   - 省略形の括弧は文法の段階（§3）の強さで決める。演算子は左結合なので、同じ強さの被演算子は右側だけ括弧で
//!     囲む。`/` で終わる式（ルートだけのパス）は、後ろの `*` や `div` が名前テストとして読まれないよう、強さに
//!     かかわらず囲む。`.` と `..` は述語を持てず、`//` は前に区切りと後ろにステップが要るので、その条件を満たす
//!     ときだけ省略する。
//!   - 数値リテラルで書けない値は、解析し直すと同じ値になる形で書く（2026-10-05）。Rust の `inf` や `NaN` は名前
//!     テストとして読まれてしまうため。正の無限大は構文解析からも作られる（倍精度に収まらない桁数の数字）ので、
//!     読むと無限大になる数字の並び（`18` の後に 0 が 307 個）で書き、同じ木に戻す。NaN、負の無限大、負のゼロは
//!     構文解析からは作られないので、`(0 div 0)`、`(-1 div 0)`、`-0` と同じ値の式で書き、木が変わるのは許す。
//!     すべてを割り算で書く案は、構文解析から作られる無限大まで別の木になるので採らない。
//!   - `'` と `"` の両方を含む文字列は、片方の引用符だけを含む部分に区切って `concat` で書く（2026-10-07）。
//!     XPath 1.0 のリテラルにはエスケープがない（同じ引用符を重ねる書き方は 2.0 から）ため。構文解析からは作られ
//!     ない値なので、値が同じなら関数呼び出しの木になるのは許す。処理命令のノードテストのターゲットは文法上
//!     リテラルしか書けないので、両方を含むターゲットは書き戻せないまま残す（ターゲットは名前で、引用符を含む
//!     処理命令は存在しない）。
//! - `XPointer` の `Display` は書かれたとおりのポインタを出す（XPointer には木の書き戻しがないため）。
//! - 式の入れ子の深さに上限を置く（`xpath::Limits::max_depth`、既定 64、`None` で無制限。2026-10-07）。ほかの上限
//!   と同じく既定で有限にし、`XPath::parse` に `Limits` を渡す（`FromStr` は既定値）。
//!   - 構文解析・評価・書き戻し・破棄は、どれも式の入れ子の深さだけ再帰する。Rust ではスタックが尽きると panic
//!     ではなく異常終了になり、呼び出し側が回復できない（`dom` の「Traversal depth」と同じ理由）。
//!   - 深さは、式そのものを 1 段目とし、括弧、述語、関数呼び出しの引数、単項マイナス、二項演算子の被演算子が 1 段
//!     ずつ深くする。構文解析の再帰（括弧など）は解析しながら数えて、超えたトークンの位置で `Error::Limit` にする。
//!     二項演算子の連なりはループで読むので解析は深くならないが、木は左に深く連なり評価や書き戻しがその深さだけ
//!     再帰するので、解析後の木の深さも（再帰せずに）調べ、式の先頭の位置で `Error::Limit` にする。
//!   - 既定値 64 の根拠: 1 MiB のスタック（Windows のメインスレッドの既定。呼び出し側が使う中で最も小さい）で
//!     測った 1 段あたりの最大は、debug ビルドで述語の入れ子の解析と評価の約 8.8 KiB（release 約 2.7 KiB）。64 段で
//!     約 563 KiB（release 約 173 KiB）で、1 MiB の半分強に収まり、呼び出し側の分の余裕が残る。実用の式の入れ子は
//!     多くて十数段。JDK も同種の上限を既定で持つ（`jdk.xml.xpathExprGrpLimit` は括弧の入れ子 10、
//!     `jdk.xml.xpathExprOpLimit` は演算子の数 100）。64 は括弧について JDK より緩く、`or` の羅列は 63 項まで通る。
//!     既定値の深さの式をすべての種類について 1 MiB のスタックで解析・評価・書き戻し・破棄するテスト
//!     （`expressions_at_the_default_depth_fit_in_a_one_mib_stack`）で、フレームが太って溢れるようになったら検出する。
//!   - 上限を決める前に 1 段あたりのスタックを減らした。debug ビルドは `match` の全 arm の局所変数と一時値を 1 つの
//!     フレームに確保するので、評価器の `eval` と `binary` の arm の処理を別関数に分け（`1+1+…` の評価が 1 MiB で
//!     125 項から 570 項）、構文解析は演算子の段階ごとの再帰を優先順位上昇法に改めた（括弧の入れ子が 62 段から
//!     154 段）。
//! - 評価器は文書の木を再帰せずにたどる（子孫の列挙と文書順の番号付け。2026-10-07）。`dom` の「Traversal depth」
//!   と同じ方針で、組み立てた木の深さには上限がないため。再帰していたときは、1 MiB のスタックで `count(//*)` が
//!   深さ約 1,300（debug）の木で異常終了した。式の深さと違って利用者が上限を決められないので、上限ではなく反復で
//!   扱う。
//!   - 文書順の番号付けでは、名前空間ノードを親から引き継いだ接頭辞の一覧に要素自身の宣言を当てはめて求める。
//!     要素ごとに祖先をたどると、ノード数 × 深さの時間になる（深さ 5,000 の木で `count(//*)` が debug で約 1.5 秒）
//!     ため。宣言を持たない要素は親の一覧を `Rc` で共有する。改めた後は同じ木で約 21 ms。
//! - 軸はノードを列に集めて返さず、見つけた順に 1 つずつ関数に渡す（`axis::walk`。2026-10-11）。ステップの評価は
//!   ノードテストで絞りながら受け取るので、`//e` で文書全体の列を作らない。どの軸も同じ形で渡すので、軸の組み合わせ
//!   （`ancestor-or-self`、`following` の兄弟と子孫）も同じ関数を続けて渡すだけになる。
//!   - `following` と `preceding` は並べ直さない。下の段から上の段へたどれば、それぞれ文書順と逆文書順になる
//!     （ある段の兄弟は親の中にあり、親の兄弟より文書順で前にあるため）。`preceding` は兄弟の部分木を逆から渡す。
//!   - 属性と名前空間ノードの `following` は、その要素の子孫から始まる（§2.2。どちらも要素の子より文書順で前にあり、
//!     子の祖先ではないため）。兄弟を持たないので、以前は要素の子孫が抜けていた。
//! - 関数の名前と引数の数は構文解析の時点で調べる（`functions::check`、2026-10-11）。どちらも式だけで決まるので、
//!   文書によらず評価の前にエラーにできる。評価のときに調べると、存在しない関数でも引数をすべて評価し、引数の
//!   評価のエラー（束縛されていない変数など）が引数の数の誤りより先に出ていた。評価の側も同じ表で調べ直すので、
//!   2 か所の判定は食い違わない。接頭辞付きの関数（拡張関数）も、提供していないので解析の時点で拒否する。
//! - `round` は `(x + 0.5).floor()` ではなく、`floor` との差を 0.5 と比べて丸める。足し算そのものが丸められ、0.5 未満で
//!   最大の倍精度の値 0.49999999999999994 が 1 になるため（昔の Java の `Math.round` と同じ誤り）。
//! - `id()` は、評価 1 回の中で、最初に引くときに ID の表を作って引く（`DomModel` が `OnceCell` で持つ）。ID ごとに
//!   `get_element_by_id` で木を歩くと、ID の数 × 文書の大きさの時間になるため。表は評価の間だけ使うので、DOM の
//!   ID 索引の TODO（変更のたびに表を保つ）とは別に、木の変更に追従させずに済む。
//! - 評価のエラーは、それを起こした式の中の位置に置く（2026-10-11）。XSLT の属性のように文書の中に書かれた長い式
//!   で、誤りの場所を示せるようにするため。
//!   - 評価でエラーになりうるノード（二項演算子、フィルタ式、変数、関数呼び出し、パス）に、式の中のバイト位置を
//!     持たせる。位置は `Location` ではなくバイト位置で持つ。`Location` は識別子の文字列を含んで大きく、木が
//!     大きくなると解析と評価の 1 段あたりのスタックが増えるため。エラーのときだけ、`XPath` が持つ元の文字列から
//!     文字を数えて `Location` にする（`Context::locate`）。
//!   - 位置の付いていないエラーにだけ位置を付け、すでに付いた位置は上書きしない。内側で起きたエラーは、外側の
//!     ノードではなく、起きた場所を指す。どのノードにも当たらないエラーは、`evaluate` が式の先頭に置く。
//!   - 名前テストと変数名の接頭辞は解析の時点で調べ、書かれた位置のエラーにする。束縛は式を評価する前に決まる
//!     ので、文書によって結果が変わらないため（以前は、候補のノードがなければエラーにならなかった）。
//!   - 往復のテストは、位置を消した木どうしを比べる。書き戻した式は元の式と文字の位置が違うため。
//! - 文字列の関数は文字を Unicode のコードポイントで数える（XPath 1.0 の文字は XML の文字）。UTF-16 の単位で数える
//!   Java とは、補助面の文字を含む文字列で結果が違う（`string-length('😀')` はここで 1、Java で 2）。
//!
//! ## 構成
//!
//! - ライブラリを 1 クレート（`xenolith`）にし、上位層（XPath、XSLT、XInclude、CLI）をレビューの間ワークス
//!   ペースの外に退避した理由。
//! - `DomSource` は文書型ノードを既定では飛ばし、`with_doctype(dtd, pool)` を渡したときだけ `Doctype` イベントに
//!   する。イベントが解析済み DTD を要求する一方、木は DTD を保持しないため。木が持つのは宣言の名前と識別子だけで、
//!   それがイベントに載る。
//!   - 常に空 DTD で報告しない理由: 下流に `ValidatorSet::validating_dtd(true)` がいると、宣言が空の DTD を持つ
//!     文書として扱われ全要素が未宣言になる。イベントが来なければ「DTD なし」として検証されない。opt-in が安全。
//!   - ファサードの `Writer` は `with_doctype(bool)`。writer はイベントから名前と識別子だけを読むので、空の
//!     `Dtd::default()` で足りる（内部サブセットは元から書かない）。
//! - `get_element_by_id` は索引を持たず、呼ぶたびに木を歩く（一致した最初の要素で打ち切る）。当面は計算量を
//!   ドキュメントに明記するだけにした。索引は引きを O(1) にするが、`set_id_attribute`、`set_attribute`（ID 属性の
//!   値の変更）、`remove_attribute`、部分木が着脱される `append_child`/`insert_before`/`replace_child`/
//!   `remove_child`、`import_node` のすべてで真であり続けなければならず、重複 ID のときに返す要素も変わる
//!   （今は文書順で最初）。O(1) 化は TODO として残す。
//! - 挿入の循環の検査（挿入するノードが挿入先の祖先でないか）は、挿入するノードが子を持つときだけ祖先をたどる
//!   （2026-10-07）。子のないノードは自分以外の祖先になりえないため。たどる時間は木の深さに比例するので、要素を
//!   1 つずつ下へ足して深い木を組み立てると全体で深さの 2 乗になっていた（深さ 50,000 で debug 約 22 秒、改めた後は
//!   約 31 ms）。
//! - `getElementsByTagName` は DOM では Document と Element の両方にあるので、`Document` 側は起点の `NodeId` を
//!   取る 1 つのメソッドにし（`document_node()` を渡せば文書全体）、`NodeRef` 側に `Element` と同じ読み口を置く。
//!   `Document` の他のメソッドがすべて `NodeId` を取るのと揃う。`getElementById` は Document のみ（仕様どおり。
//!   `Element` にはない）。
//! - ファイル配置: `module.rs` とそのテスト `module/test.rs`、その隣にサブモジュール。
//! - 可視性を絞った構造体（`pub(crate) struct` / `pub(super) struct`）のフィールドは `pub` と書く。フィールドの
//!   実効可視性は型の可視性で上限が決まるので `pub(crate)` と書いても意味は変わらず、型と重複した情報になる。
//!   - メソッドは絞ったまま（`pub(crate) fn`）にする。`unreachable_pub` はフィールドには発火しないが、項目には
//!     発火するので、`pub(crate)` 型の `pub fn` は警告になる（実測で確認）。フィールドだけが簡略化できる。
//! - `io::sax` は削除した。コードを持たず、モジュール説明（SAX 移行ガイド）と `crate::event` の再公開だけの
//!   モジュールで、同じ型に公開パスが 2 本ある状態だった（クレート内の import も 2 通りに割れていた）。
//!   ROADMAP が計画していた「SAX 相当の push アダプタ」は `EventConsumer` + `emit` として event 語彙に吸収済み。
//!   - ガイドの内容は `MIGRATING-FROM-JAVA.md`（元から同じ対応表を持つ）に寄せた。代償として、その節の例は
//!     コンパイルされなくなる（この md は rustdoc に取り込まれていない）。振る舞いは移したユニットテストが見る。
//!   - モジュールのテスト 8 件は「パーサが消費者を駆動する」ことの検証なので `io::read` のテスト（`mod push`）へ
//!     移した。
//! - ファサードは内部で使う部品のオプションを `with_*` で中継する（`Reader`: `with_encoding`、`with_config`、
//!   `with_resolver`、`with_xinclude`、
//!   `Writer`: `with_standalone`、`with_declaration_line_break`、`with_encoding`、`with_declared_encoding`、
//!   `with_doctype`）。
//!   - `DomBuilder::with_xml_id` はファサードには出さず、`ParserConfig` の `extensions.xml_id` を適用する。
//!     同じことを 2 箇所で設定させないため。`DomBuilder` を手で配線する場合はパーサの設定を見られないので、
//!     引き続き自分で渡す。
//!   - 失敗しうる設定（エンコーディング名）はラベルを保持するだけにして、エラーは読み書きの呼び出しから返す。
//!     builder を `Result` にすると連鎖が崩れ、設定時と使用時のどちらで失敗するかも曖昧になる。
//!   - `Writer` は `String` を持つので `Copy` を外した（`Clone` は維持）。
//!   - `Reader` の `Default` は derive しない。derive では `strict`/`xml_id` が `false` になり、`new()`（どちらも
//!     有効）と食い違う。
//!   - リゾルバは `StreamSource` が所有していたが、消費者と同じ借用に変えた。所有だと source と一緒に drop
//!     されるので、読みごとに作り直すか `Reader` を消費する形にするしかなく、カタログやキャッシュを持つリゾルバを
//!     使い回せない。さらに XInclude は外側のパースと入れ子のパースで同じリゾルバを必要とするので、所有では共有
//!     できない。アプリが持ち、実行の間だけ貸す。
//!   - **`UriResolver::resolve` は `&self` を取る。** 最初は `&mut self` にしていたが、`&mut` は同時に 1 つしか
//!     存在できないので「1 つのリゾルバを複数の借り手が使う」が書けず、回避のために `RefCell`（実行時に 1 つずつ）、
//!     `Rc`（`self` を貸した後でも掴めるハンドル）、それを渡す入口（`with_shared_resolver`）、セルを
//!     `UriResolver` に見せるアダプタ（`Lent`）が積み上がっていた。**全部 `&mut self` の派生物だった。**
//!     - `&self` なら共有参照は `Copy` かつ共変なので、パーサにも入れ子のパースにも同じ参照を渡すだけで済み、上の
//!       4 つが全部消える。実行時の borrow panic の危険もなくなる。`XIncludeTransformer` の寿命引数を 2 つに割った
//!       理由（`RefCell` が不変で `'h` を縛る）も消えた。
//!     - 代償は、状態を持つリゾルバが自分で内部可変性（`RefCell` など）を書くこと。キャッシュや記録を持つ実装だけが
//!       払い、借り手側は誰も背負わない配分になる。以前は逆で、状態を持たないリゾルバのためにも全借り手が共有機構を
//!       背負っていた。
//!     - 非同期側（`AsyncUriResolver`）も `&self` に揃えた。同期と非同期でリゾルバの書き方が変わらないようにする。
//!   - リゾルバは `Option` で持たず、常に 1 つある形にした（`NoResolver::shared()`）。「リゾルバがない」分岐が
//!     `StreamSource` と `XIncludeTransformer` とファサードから消え、「解決しない」という振る舞いと、`with_resolver`
//!     を呼べというメッセージが `NoResolver` 自身に集まる。定数ではなくメソッドで渡すのは、公開するものを型と
//!     メソッドに留めるため。
//!     - 非同期側に同名の型があったので 1 つに統合した（`impl UriResolver` と `impl AsyncUriResolver` の両方を
//!       持つ 1 つの型）。型 1 つに公開パス 2 本、という `io::sax` で解消した状態を作らないため。
//! - `Transformer` を語彙として定義した。`EventConsumer` かつ `EventProducer`、すなわちパイプラインの中段のこと
//!   （SAX の `org.xml.sax.XMLFilter` の役割）。`XIncludeTransformer` が最初の実装で、`XSLTransform` もこの形で
//!   実装する想定。整形や名前空間の補完もここに入る。
//!   - トレイト `Transformer: EventProducer + EventConsumer` は作らない。境界として書けば同じことが言えるので能力が
//!     増えない。動的なパイプライン（`Vec<Box<dyn Transformer>>`）も作れない: `EventProducer::add_consumer` は
//!     `self` を取る `where Self: Sized` なので vtable に載らず、`dyn` では後段を配線できない。名前だけの
//!     マーカーになるため、語彙のままにして、中段が守るべきことは `event` のモジュールドキュメントに書く。
//!   - 動的なパイプラインが必要になったら、足すのはトレイトではなく `set_handler(&mut self, ..)` のような
//!     オブジェクト安全な配線メソッドである。
//! - `Reader` と `Writer` は `facade.rs` に同居させる（旧 `reader.rs` / `writer.rs`）。
//!   - どちらも「下層の部品は揃っていて、アプリはバイト列⇔木が欲しいだけ。ファサードは組み合わせるだけで独自機能を
//!     持たない」という同じ論旨を必要とし、2 ファイルに書くと重複する。モジュール説明で 1 回だけ述べる。
//!   - モジュールは private（`pub use facade::{Reader, Writer}`）なので、公開パス `xenolith::Reader` /
//!     `xenolith::Writer` は変わらない。結合テストも以前から `tests/reader_writer.rs` で対として扱っていた。
